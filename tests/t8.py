import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width':1280,'height':720})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file:///home/claude/bandvan/dist/index.html')
        await pg.wait_for_function("document.getElementById('loading').style.display==='none'", timeout=90000)
        await pg.evaluate("document.getElementById('go').click()"); await pg.wait_for_timeout(600)
        ev=pg.evaluate
        st = lambda: ev("(()=>{const P=__dbg.P, v=__dbg.van; const l=v.root.worldToLocal(P.pos.clone()); return [P.mode, P.onboard, +l.x.toFixed(2), +l.y.toFixed(2), +l.z.toFixed(2)]})()")
        await pg.screenshot(path='shots/60_start.png')
        print('start', await st())
        await pg.keyboard.down('KeyW')
        for k in range(8):
            await pg.wait_for_timeout(500); print('walk', await st())
        await pg.keyboard.up('KeyW')
        await pg.screenshot(path='shots/61_inside.png')
        # turn toward cab (+z local => yaw = heading)
        await ev("__dbg.P.yaw = __dbg.van.heading; __dbg.P.pitch=-0.1"); await pg.wait_for_timeout(400)
        await pg.screenshot(path='shots/62_cab_look.png')
        await pg.keyboard.down('KeyW'); await pg.wait_for_timeout(500); await pg.keyboard.up('KeyW')
        await ev("__dbg.P.yaw = __dbg.van.heading - 0.6; __dbg.P.pitch=-0.5"); await pg.wait_for_timeout(500)
        print('hover', await ev("__dbg.hover"), await st())
        await pg.screenshot(path='shots/63_seat_prompt.png')
        await ev("__dbg.P.yaw = __dbg.van.heading + Math.PI; __dbg.P.pitch=-0.15"); await pg.wait_for_timeout(400)
        await pg.screenshot(path='shots/64_rear.png')
        await ev("__dbg.sit('driver')"); await pg.wait_for_timeout(500)
        await pg.screenshot(path='shots/65_driver.png')
        await pg.keyboard.press('KeyR'); await pg.wait_for_timeout(2500)
        await pg.keyboard.down('KeyQ'); await pg.wait_for_timeout(300)
        await pg.mouse.move(640,360); await pg.mouse.down(button='right')
        for i in range(10): await pg.mouse.move(640-14*(i+1),360); await pg.wait_for_timeout(30)
        for i in range(10): await pg.mouse.move(500,360-16*(i+1)); await pg.wait_for_timeout(30)
        await pg.screenshot(path='shots/66_clutch_overlay.png')
        await pg.mouse.up(button='right'); await pg.keyboard.up('KeyQ')
        await pg.keyboard.press('KeyP')
        print('gear/engine/hb', await ev("[__dbg.van.gear, __dbg.van.engineOn, __dbg.van.handbrake]"))
        await pg.keyboard.down('KeyW'); await pg.wait_for_timeout(5000); await pg.keyboard.up('KeyW')
        print('speed', await ev("__dbg.van.v*3.6"))
        await pg.screenshot(path='shots/67_driving.png')
        # stand up while moving and check carry
        await pg.keyboard.press('KeyE'); await pg.wait_for_timeout(1500)
        print('after exit', await st())
        await ev("__G.dbg.third=false; __dbg.van.v=0; __dbg.P.yaw=__dbg.van.heading + Math.PI*0.75"); 
        await ev("(()=>{const v=__dbg.van; const P=__dbg.P; v.local(-7,0,-2,P.pos); P.pos.y=__dbg.world.walkH(P.pos.x,P.pos.z,50); P.onboard=false; P.yaw=v.heading+Math.PI/2-0.3; P.pitch=0.15;})()"); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/68_outside_scale.png')
        print(errs)
        await b.close()
asyncio.run(main())

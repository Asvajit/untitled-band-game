import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width':1280,'height':720})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('file:///home/claude/bandvan/dist/index.html')
        await pg.wait_for_function("document.getElementById('loading').style.display==='none'", timeout=90000)
        await pg.evaluate("document.getElementById('go').click()"); await pg.wait_for_timeout(400)
        ev=pg.evaluate
        await ev("__dbg.sit('driver')"); await pg.wait_for_timeout(500)
        await pg.screenshot(path='shots/70_wheel.png')
        await ev("__dbg.teleport('rest')"); await pg.wait_for_timeout(400)
        await ev("""(()=>{const w=__dbg.world, s=w.shopSpots[0], F=w.restFrame; const P=__dbg.P; P.pos.set(s.x - F.rx*1.3, w.groundY.rest, s.z - F.rz*1.3); P.yaw=Math.atan2(F.rx,F.rz); P.pitch=-0.35;})()"""); await pg.wait_for_timeout(500)
        print('shop hover', await ev("__dbg.hover"))
        await pg.screenshot(path='shots/71_shop_fp.png')
        await pg.keyboard.press('KeyE'); await pg.wait_for_timeout(300)
        await ev("""(()=>{const v=__dbg.van, P=__dbg.P; const p=v.local(0.9,0,-6.6); P.pos.set(p.x, __dbg.world.walkH(p.x,p.z,50), p.z); P.yaw=v.heading; P.pitch=-0.15;})()"""); await pg.wait_for_timeout(500)
        print('port hover', await ev("__dbg.hover"))
        await pg.screenshot(path='shots/72_port_fp.png')
        await pg.keyboard.press('KeyE'); await pg.wait_for_timeout(300)
        print('fuel obj', await ev("[__dbg.van.fuel, __G.obj]"))
        await ev("__dbg.teleport('stage')"); await pg.wait_for_timeout(300)
        await ev("__dbg.P.yaw = 0; __dbg.P.pitch=-0.3"); await pg.wait_for_timeout(500)
        print('stage hover', await ev("__dbg.hover"))
        await ev("__G.dbg.autoplay=true"); await pg.keyboard.press('KeyE'); await pg.wait_for_timeout(5000)
        print('perf', await ev("__G.perf && __G.perf.score"))
        await pg.screenshot(path='shots/73_gig.png')
        await ev("__G.perf.finish()"); await pg.wait_for_timeout(300)
        await pg.click('#rcont'); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/74_after.png')
        print(errs)
        await b.close()
asyncio.run(main())

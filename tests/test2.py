import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader','--autoplay-policy=no-user-gesture-required'])
        pg = await b.new_page(viewport={'width':1280,'height':720})
        logs=[]
        pg.on('console', lambda m: logs.append(f'{m.type}: {m.text}') if m.type in ('error',) else None)
        pg.on('pageerror', lambda e: logs.append(f'PAGEERROR: {e}'))
        await pg.goto('file:///home/claude/bandvan/dist/index.html')
        await pg.wait_for_function("document.getElementById('loading').style.display==='none'", timeout=90000)
        await pg.click('#go'); await pg.wait_for_timeout(800)
        await pg.screenshot(path='shots/10_walk.png')
        await pg.evaluate("__dbg.boardVan(true); __dbg.sit('driver')"); await pg.wait_for_timeout(600)
        await pg.screenshot(path='shots/11_cab.png')
        await pg.evaluate("const v=__dbg.van; v.engineOn=true; v.rpm=900; v.handbrake=false; v.gear='1'")
        await pg.keyboard.down('KeyW'); await pg.wait_for_timeout(2500); await pg.keyboard.up('KeyW')
        print('after drive', await pg.evaluate("[__dbg.van.v, __dbg.van.rpm, __dbg.van.gear, __dbg.van.engineOn, __dbg.van.pos.z]"))
        await pg.screenshot(path='shots/12_driving.png')
        await pg.keyboard.press('KeyV'); await pg.wait_for_timeout(1200)
        await pg.screenshot(path='shots/13_chase.png')
        await pg.evaluate("__dbg.teleport('rest'); __dbg.P.camYaw = __dbg.van.heading + Math.PI/2 + 0.3"); await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/14_rest.png')
        await pg.keyboard.press('KeyM'); await pg.wait_for_timeout(300)
        await pg.screenshot(path='shots/15_map.png'); await pg.keyboard.press('Escape')
        await pg.evaluate("__dbg.teleport('venue'); __dbg.P.camYaw = 0; __G.todOverride=0.93"); await pg.wait_for_timeout(2500)
        await pg.screenshot(path='shots/16_venue.png')
        await pg.evaluate("__dbg.teleport('backstage'); __dbg.P.camYaw = -0.4"); await pg.wait_for_timeout(1500)
        await pg.screenshot(path='shots/17_backstage.png')
        await pg.evaluate("__G.dbg.autoplay=true; __dbg.startGig()"); await pg.wait_for_timeout(7000)
        await pg.screenshot(path='shots/18_gig.png')
        await pg.wait_for_timeout(5000)
        await pg.screenshot(path='shots/19_gig2.png')
        print('perf', await pg.evaluate("__G.perf && [__G.perf.score, __G.perf.stats, __G.perf.hype]"))
        await pg.evaluate("__dbg.abortPerf(); __dbg.setupRole('vocals'); __dbg.startPractice()"); await pg.wait_for_timeout(6000)
        await pg.screenshot(path='shots/20_practice_vocals.png')
        await pg.evaluate("__dbg.abortPerf(); __dbg.setupRole('trumpet'); __dbg.startPractice()"); await pg.wait_for_timeout(5000)
        await pg.screenshot(path='shots/21_practice_trumpet.png')
        await pg.evaluate("__dbg.abortPerf(); window.dispatchEvent(new KeyboardEvent('keydown',{code:'Backquote'}))"); await pg.wait_for_timeout(500)
        await pg.screenshot(path='shots/22_debug.png')
        for l in logs[:30]: print(l)
        await b.close()
asyncio.run(main())

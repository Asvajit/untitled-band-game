import asyncio
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(executable_path='/usr/bin/google-chrome', args=['--use-gl=angle','--use-angle=swiftshader','--enable-unsafe-swiftshader'])
        pg = await b.new_page(viewport={'width':1280,'height':720})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.goto('http://localhost:8765/index.html')
        await pg.wait_for_function("document.getElementById('loading').style.display==='none'", timeout=180000)
        await pg.click('#goedit'); await pg.wait_for_timeout(600)
        print('editor warns', await pg.evaluate("__dbg.editor._dbg.info.warns"))
        await pg.screenshot(path='shots/ed_new.png'); print(errs); await b.close()
asyncio.run(main())
